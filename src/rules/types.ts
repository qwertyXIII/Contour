/**
 * Правило Contour — «что + куда» (решение владельца 2026-10-02): один движок
 * для всех входов — HTTP-прокси, умного DNS и SNI (телевизор), шлюза и раздачи
 * (из него собирается конфиг телефона). Каждый вход переводит «куда» на свой
 * язык: DNS — настоящие адреса или наш, шлюз — класс маршрута, телефон —
 * DIRECT / Contour / группа страны / REJECT.
 */

/** Куда вести. */
export type Target =
  /** Мимо туннелей: интернет той сети, где соединение (у прокси — прямой выход сервера). */
  | { kind: 'direct' }
  /** Через туннели Contour, как сейчас для заблокированного: выход — по приоритету и прилипанию. */
  | { kind: 'tunnel' }
  /** Выйти в этой стране — выходом этой страны; нет такого — отказ, не другая страна. */
  | { kind: 'country'; country: string }
  /** Через туннели, но не через выходы этих стран (сервис сам не пускает их адреса). */
  | { kind: 'avoid'; countries: string[] }
  /** Только через эти выходы, никогда напрямую (корпоративная сеть — только корпоративными туннелями). */
  | { kind: 'only'; outlets: string[] }
  /** Отказать сразу. */
  | { kind: 'reject' };

/** `fastest` — среди подходящих выходов той же страны брать самый быстрый (режим у правила, не у всего Contour). */
export type Action = { target: Target; fastest?: boolean };

/** Что совпадает: имя (`exact` — только оно само, иначе и поддомены) или подсеть IPv4. */
export type Match =
  | { kind: 'domain'; name: string; exact: boolean }
  | { kind: 'cidr'; net: number; bits: number };

export type Entry = { match: Match; action: Action };
